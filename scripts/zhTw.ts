const TRADITIONAL_CHARACTERS = Object.fromEntries(
  CHARACTER_PAIRS.trim().split(/\s+/u).map((pair) => [pair[0], pair[1]])
) as Readonly<Record<string, string>>;

const orderedTaiwanTerms = [...TAIWAN_TERMS].sort((left, right) => right[0].length - left[0].length);

export function toTraditionalChinese(source: string): string {
  let converted = source;
  for (const [simplified, traditional] of orderedTaiwanTerms) {
    converted = converted.split(simplified).join(traditional);
  }
  return converted.replace(/[\u3400-\u9fff]/gu, (character) => TRADITIONAL_CHARACTERS[character] ?? character);
}
